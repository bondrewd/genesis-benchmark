def archive_native_available(spec):
    """Return True when the canonical source archive can supply this native variant."""
    if not spec.assets:
        return False
    verify_archive_pin(spec.system)
    members = ARCHIVE_PINS[spec.system]["members"]
    for item in spec.assets:
        for path in item.paths():
            relative = repo_relative(path)
            if not relative.startswith("data/%s/" % spec.system):
                raise GenerationError(
                    "%s/%s archive asset is outside its pinned system tree: %s" %
                    (spec.system, spec.variant, relative)
                )
            member = relative[len("data/"):]
            if member not in members:
                raise GenerationError(
                    "%s/%s archive asset has no pinned member hash: %s" %
                    (spec.system, spec.variant, member)
                )
            # An archive pin proves the source bundle, not an ignored extracted
            # file.  Only advertise a direct archive asset when the concrete
            # file exists and is byte-identical to the pinned member.
            if not os.path.isfile(path):
                return False
            if _sha256(path) != members[member]:
                return False
    return True


def merge_neutral_archive_assets(
        prepared_variant, archive_variant, include_archive_assets=True):
    """Overlay validated prepared assets on a formally neutral native archive."""
    formal_charges = (
        prepared_variant.source_formal_charge_e,
        prepared_variant.pre_neutralization_formal_charge_e,
        prepared_variant.post_neutralization_formal_charge_e,
        archive_variant.source_formal_charge_e,
    )
    if any(charge != 0 for charge in formal_charges):
        return prepared_variant
    if prepared_variant.atom_count != archive_variant.atom_count:
        raise GenerationError(
            "%s: prepared atom count does not match its native archive" %
            prepared_variant.manifest_path
        )
    if any(abs(left - right) > 1.0e-5 for left, right in zip(
            prepared_variant.box_angstrom, archive_variant.box_angstrom)):
        raise GenerationError(
            "%s: prepared box does not match its native archive" %
            prepared_variant.manifest_path
        )
    if abs(prepared_variant.source_charge_e - archive_variant.source_charge_e) > 1.0e-3:
        raise GenerationError(
            "%s: prepared source charge does not match its native archive" %
            prepared_variant.manifest_path
        )
    native_by_engine = {item.engine: item for item in archive_variant.assets}
    by_engine = dict(native_by_engine) if include_archive_assets else {}
    for prepared_asset in prepared_variant.assets:
        native_asset = native_by_engine.get(prepared_asset.engine)
        if native_asset is not None:
            # Prepared files are self-contained.  Only audited scalar metadata
            # is inherited from the pinned native declaration; source-file
            # paths such as legacy restart/reference coordinates are never
            # smuggled into a prepared asset.
            prepared_asset = replace(
                prepared_asset,
                amber_scee=(prepared_asset.amber_scee
                            if prepared_asset.amber_scee is not None
                            else native_asset.amber_scee),
                amber_scnb=(prepared_asset.amber_scnb
                            if prepared_asset.amber_scnb is not None
                            else native_asset.amber_scnb),
            )
        by_engine[prepared_asset.engine] = prepared_asset
    merged = tuple(by_engine[engine] for engine in ENGINE_ORDER if engine in by_engine)
    return replace(prepared_variant, assets=merged)


def available_variants():
    """Return available variants and missing prepared declarations in stable order."""
    available = []
    missing = []
    for declaration in VARIANT_DECLARATIONS:
        fallback = ARCHIVE_FALLBACKS.get((declaration.system, declaration.variant))
        loaded = load_prepared_variant(declaration)
        if loaded is not None:
            if fallback is not None:
                loaded = merge_neutral_archive_assets(
                    loaded, fallback,
                    include_archive_assets=archive_native_available(fallback),
                )
            available.append(loaded)
            continue
        if (fallback is not None and fallback.post_neutralization_formal_charge_e == 0
                and archive_native_available(fallback)):
            available.append(fallback)
        else:
            missing.append(declaration)
    return tuple(available), tuple(missing)


def repo_relative(path):
    """Return a normalized repository-relative path for generated controls."""
    resolved = os.path.realpath(path)
    root = os.path.realpath(HERE)
    if resolved != root and not resolved.startswith(root + os.sep):
        raise GenerationError("asset is outside the benchmark repository: %s" % path)
    return os.path.relpath(resolved, root).replace(os.sep, "/")


def number(value):
    """Format a finite floating-point value deterministically."""
    numeric = float(value)
    if not math.isfinite(numeric):
        raise GenerationError("non-finite numeric value: %r" % value)
    if numeric == 0.0:
        return "0"
    text = repr(numeric)
    return text[:-2] if text.endswith(".0") else text


def dt_label(dt_fs):
    """Return a filename-safe femtosecond label."""
    return number(dt_fs).replace("-", "m").replace("+", "p").replace(".", "p") + "fs"


def cell_stem(system, variant, ensemble, dt_fs, execution_profile="matched"):
    """Return the stable filename stem shared by every engine.

    ``variant`` remains an internal provenance key.  It is deliberately absent
    from filenames because every system exposes exactly one native model.
    The closest GENESIS-matched route keeps the compact historical stem; a
    scientifically distinct engine-native route receives an explicit suffix.
    """
    del variant
    stem = "%s__%s__%s" % (system, ensemble, dt_label(dt_fs))
    return stem if execution_profile == "matched" else stem + "__" + execution_profile


def switch_semantic(variant):
    """Return the native van-der-Waals switching semantic for a variant."""
    if variant.family != "CHARMM":
        return "none"
    if variant.forcefield in ("CHARMM36", "CHARMM36lipid"):
        return "force"
    return "potential"


