@dataclass(frozen=True)
class SystemSpec:
    """System-level geometry and established PME layout metadata."""

    box_angstrom: tuple
    pme_grid: tuple = None
    explicit_domain: bool = False


@dataclass(frozen=True)
class AssetSpec:
    """Concrete files consumed by one engine renderer."""

    engine: str
    format: str
    topology: str
    coordinates: str = None
    topology_definitions: tuple = ()
    parameters: tuple = ()
    topology_hmr: str = None
    reference: str = None
    coordinate_reference: str = None
    amber_scee: float = None
    amber_scnb: float = None
    archive_native: bool = False

    def paths(self):
        """Return every concrete path named by this asset."""
        values = [
            self.topology, self.coordinates, self.topology_hmr, self.reference,
            self.coordinate_reference,
        ]
        values.extend(self.topology_definitions)
        values.extend(self.parameters)
        return tuple(value for value in values if value)


@dataclass(frozen=True)
class VariantSpec:
    """One physical parameterization, independent of execution engine."""

    system: str
    variant: str
    family: str
    forcefield: str
    water_model: str
    solvent: str
    atom_count: int = None
    box_angstrom: tuple = None
    assets: tuple = ()
    manifest_path: str = None
    source_charge_e: float = None
    source_formal_charge_e: int = None
    pre_neutralization_charge_e: float = None
    pre_neutralization_formal_charge_e: int = None
    post_neutralization_charge_e: float = None
    post_neutralization_formal_charge_e: int = None
    neutralization_ion: str = None
    neutralization_ion_charge_e: float = None
    neutralization_ion_count: int = 0
    replaced_water_count: int = 0
    neutralization_method: str = None
    hmr_method: str = None
    hmr_hydrogen_mass_dalton: float = None

    def asset_for(self, engine):
        """Return this variant's asset for an engine, if one exists."""
        return next((asset for asset in self.assets if asset.engine == engine), None)


