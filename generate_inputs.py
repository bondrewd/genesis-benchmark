def validate_choices(values, allowed, option, parser, case_insensitive=False):
    """Reject unknown values with a deterministic choices message."""
    compare = {value.lower() if case_insensitive else value: value for value in allowed}
    unknown = [value for value in values or ()
               if (value.lower() if case_insensitive else value) not in compare]
    if unknown:
        parser.error("%s has unknown value(s) %s (choices: %s)" %
                     (option, ",".join(unknown), ",".join(allowed)))


def parse_dt(text, parser):
    """Parse, validate, and de-duplicate time steps."""
    values = []
    for token in comma_values(text) or ():
        try:
            value = finite_positive(token)
        except argparse.ArgumentTypeError as error:
            parser.error("--dt %r %s" % (token, error))
        if value > 4.0:
            parser.error("--dt values above 4 fs are unsupported")
        if value not in values:
            values.append(value)
    labels = {}
    for value in values:
        label = dt_label(value)
        if label in labels and value != labels[label]:
            parser.error("--dt values %r and %r collide as %s" %
                         (labels[label], value, label))
        labels[label] = value
    if not values:
        parser.error("--dt must contain at least one value")
    return tuple(values)


def select_variants(args, parser, loaded, missing):
    """Select the sole native model for each requested system."""
    systems = comma_values(args.systems, lower=True) or SYSTEM_ORDER
    validate_choices(systems, SYSTEM_ORDER, "--systems", parser)
    selection_filter_supplied = args.systems is not None
    declarations = [item for item in VARIANT_DECLARATIONS if item.system in systems]
    if not declarations:
        parser.error("system filter matches no declared native models")

    loaded_by_key = {(item.system, item.variant): item for item in loaded}
    missing_keys = {(item.system, item.variant) for item in missing}
    strict_selection = selection_filter_supplied
    missing_selected = [item for item in declarations
                        if (item.system, item.variant) in missing_keys]
    if strict_selection and missing_selected:
        pairs = ", ".join("%s/%s" % (item.system, item.variant) for item in missing_selected)
        first_system = missing_selected[0].system
        parser.error(
            "requested native model(s) are unavailable: %s; prepare the first with "
            "`conda run -n OpenMM python prepare_variants.py --systems %s`" %
            (pairs, first_system)
        )
    selected = [loaded_by_key[(item.system, item.variant)] for item in declarations
                if (item.system, item.variant) in loaded_by_key]
    if not selected:
        parser.error("no selected system has complete native-model assets")
    return tuple(selected), strict_selection


def protocol_for(args, system, variant, ensemble, dt_fs, execution_profile="matched"):
    """Construct and validate one protocol cell."""
    default_period = max(1, int(round(20.0 / dt_fs)))
    thermostat = args.thermostat_period or default_period
    barostat = args.barostat_period or thermostat
    baroscale = args.baroscale_period or barostat
    cutoff = args.cutoff or (9.0 if variant.family == "AMBER" else 12.0)
    skin = args.pair_list_skin or DEFAULT_PAIR_LIST_SKIN
    if variant.family == "CHARMM" and cutoff <= 2.0:
        raise GenerationError("CHARMM cutoff must exceed the 2 Angstrom switching width")
    protocol = Protocol(
        ensemble, dt_fs, args.nsteps, args.output_period, thermostat, barostat,
        baroscale, cutoff, skin, args.temperature, args.pressure,
        args.seed, args.tau_t, args.tau_p, args.namd_piston_period,
        args.namd_piston_decay, execution_profile,
    )
    validate_protocol_divisibility(protocol)
    return protocol


def validate_protocol_divisibility(protocol):
    """Require event periods to tile the executable benchmark window exactly."""
    if protocol.nsteps % protocol.output_period:
        raise GenerationError("nsteps must be divisible by output_period")
    if (protocol.ensemble in ("nvt", "npt")
            and protocol.nsteps % protocol.thermostat_period):
        raise GenerationError("NVT/NPT nsteps must be divisible by thermostat_period")
    if protocol.ensemble == "npt":
        if protocol.nsteps % protocol.barostat_period:
            raise GenerationError("NPT nsteps must be divisible by barostat_period")
        if protocol.barostat_period % protocol.baroscale_period:
            raise GenerationError("NPT barostat_period must be divisible by baroscale_period")


def planned_outputs(args, parser):
    """Resolve the complete valid output matrix."""
    loaded, missing = available_variants()
    variants, strict_variants = select_variants(args, parser, loaded, missing)
    engines = comma_values(args.engines, upper=True) or ENGINE_ORDER
    validate_choices(engines, ENGINE_ORDER, "--engines", parser)
    requested_profiles = comma_values(args.profiles, lower=True)
    validate_choices(requested_profiles, PROFILE_ORDER, "--profiles", parser)
    ensembles = comma_values(args.ensembles or ",".join(ENSEMBLE_ORDER), lower=True)
    validate_choices(ensembles, ENSEMBLE_ORDER, "--ensembles", parser)
    if not ensembles:
        parser.error("--ensembles must contain at least one value")
    time_steps = parse_dt(args.dt or ",".join(number(value) for value in DEFAULT_DT_FS), parser)

    cells = []
    output_sources = {}
    skipped = []
    for variant in variants:
        system = SYSTEMS[variant.system]
        variant_cells = []
        for engine in engines:
            concrete_asset = variant.asset_for(engine)
            profiles = requested_profiles or ENGINE_PROFILES[engine]
            for execution_profile in profiles:
                for ensemble in ensembles:
                    for dt_fs in time_steps:
                        protocol = protocol_for(
                            args, system, variant, ensemble, dt_fs, execution_profile,
                        )
                        reason = engine_supports(engine, variant, concrete_asset, protocol)
                        if reason:
                            if (requested_profiles is None and engine == "NAMD"
                                    and execution_profile == "native"
                                    and ensemble != "npt"):
                                continue
                            skipped.append(
                                (variant, engine, execution_profile, ensemble, dt_fs, reason)
                            )
                            continue
                        extension, renderer = RENDERERS[engine]
                        relative_path = os.path.join(
                            engine,
                            cell_stem(
                                variant.system, variant.variant, ensemble, dt_fs,
                                execution_profile,
                            ) + extension,
                        )
                        source = (
                            variant.system, variant.variant, engine, execution_profile,
                            ensemble, dt_fs,
                        )
                        if (relative_path in output_sources
                                and output_sources[relative_path] != source):
                            parser.error(
                                "output-path collision between %r and %r: %s" %
                                (output_sources[relative_path], source, relative_path)
                            )
                        output_sources[relative_path] = source
                        if engine == "NAMD":
                            content = renderer(
                                variant, system, concrete_asset, protocol,
                                config_directory=os.path.join(
                                    os.path.realpath(os.path.expanduser(args.output_root)), engine,
                                ),
                            )
                        else:
                            content = renderer(variant, system, concrete_asset, protocol)
                        variant_cells.append((relative_path, content))
        if strict_variants and not variant_cells:
            reasons = sorted({
                reason for item, _engine, _profile, _ensemble, _dt, reason in skipped
                if item == variant
            })
            parser.error("requested variant %s/%s has no valid cells: %s" %
                         (variant.system, variant.variant, "; ".join(reasons)))
        cells.extend(variant_cells)
    fatal_skips = []
    for item, engine, execution_profile, ensemble, dt_fs, reason in skipped:
        # A timestep filter customizes the supported matrix; it does not ask
        # the generator to invent missing engine support.  An explicit engine
        # filter, on the other hand, is a request for complete coverage and
        # must fail closed when any selected cell is unavailable.
        if args.engines is not None:
            fatal_skips.append(
                (item, engine, execution_profile, ensemble, dt_fs, reason)
            )
    if fatal_skips:
        first = fatal_skips[0]
        parser.error(
            "explicit matrix contains unsupported cell %s/%s %s %s %s %s: %s%s" %
            (first[0].system, first[0].variant, first[1], first[2],
             first[3], dt_label(first[4]), first[5],
             " (and %d more)" % (len(fatal_skips) - 1) if len(fatal_skips) > 1 else "")
        )
    if not cells:
        parser.error("selection produced no valid engine inputs")
    return tuple(cells), tuple(skipped), variants


def write_atomic(path, text):
    """Atomically replace one generated text file."""
    directory = os.path.dirname(path)
    os.makedirs(directory, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".generate-", dir=directory, text=True)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as output:
            output.write(text)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def is_generated(path):
    """Return True when a regular file carries this generator's marker."""
    try:
        with open(path, encoding="utf-8") as stream:
            return GENERATED_MARKER in stream.readline()
    except (OSError, UnicodeError):
        return False


def write_outputs(output_root, cells):
    """Write planned files without pruning outputs outside the current filter."""
    for relative, content in cells:
        path = os.path.join(output_root, relative)
        if os.path.exists(path) and not is_generated(path):
            raise GenerationError("refusing to replace non-generated file: %s" % path)
        if os.path.isfile(path):
            try:
                with open(path, "rb") as existing:
                    if existing.read() == content.encode("utf-8"):
                        continue
            except OSError:
                pass
        write_atomic(path, content)


def prune_stale_outputs(output_root, cells):
    """Remove stale generated cells during an unfiltered full-matrix write."""
    planned = {
        os.path.realpath(os.path.join(output_root, relative))
        for relative, _content in cells
    }
    removed = []
    for engine in ENGINE_ORDER:
        engine_directory = os.path.join(output_root, engine)
        if not os.path.isdir(engine_directory):
            continue
        with os.scandir(engine_directory) as entries:
            for entry in entries:
                if not entry.is_file(follow_symlinks=False):
                    continue
                path = os.path.realpath(entry.path)
                if path in planned or not is_generated(entry.path):
                    continue
                os.unlink(entry.path)
                removed.append(entry.path)
    return tuple(removed)


