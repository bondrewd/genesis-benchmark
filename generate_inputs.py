def engine_supports(engine, variant, asset_spec, protocol):
    """Return a reason string for an unsupported cell, or None."""
    if protocol.execution_profile not in ENGINE_PROFILES[engine]:
        return "%s has no distinct %s execution profile" % (
            engine, protocol.execution_profile,
        )
    runtime_block = RUNTIME_ENGINE_BLOCKS.get((engine, variant.system))
    if runtime_block:
        return runtime_block
    if (engine == "NAMD" and protocol.execution_profile == "native"
            and protocol.ensemble != "npt"):
        return "NAMD has no distinct native profile outside NPT"
    if asset_spec is None:
        return "no %s asset" % engine
    if not asset_spec.archive_native and not all(os.path.isfile(path) for path in asset_spec.paths()):
        return "%s asset is incomplete" % engine
    if (variant.post_neutralization_formal_charge_e != 0
            or abs(variant.post_neutralization_charge_e) > 1.0e-3):
        return "explicit PME topology is not neutral"
    format_name = normalized_format(asset_spec.format)
    if protocol.dt_fs > 4.0 + 1.0e-12:
        return "%s supports at most 4 fs in this generator" % engine
    if protocol.dt_fs > 2.0:
        if engine == "GROMACS" and not asset_spec.topology_hmr:
            return "GROMACS 4 fs requires a validated topology_hmr asset"
        if engine in ("AMBER", "NAMD") and not asset_spec.topology_hmr:
            return "%s 4 fs requires a prepared topology_hmr asset" % engine
    if engine == "OPENMM" and switch_semantic(variant) != "none":
        return "OpenMM native renderer cannot exactly represent native CHARMM switching"
    if variant.family == "CHARMM" and engine in ("GROMACS", "AMBER"):
        return "%s lacks an exact validated native CHARMM switching asset type" % engine
    allowed = {
        "GENESIS": ("AMBER", "CHARMM", "GROAMBER"),
        "OPENMM": ("AMBER", "CHARMM"),
        "GROMACS": ("GROMACS",),
        "AMBER": ("AMBER", "CHAMBER"),
        "NAMD": ("AMBER", "CHARMM"),
    }[engine]
    if format_name not in allowed:
        return "%s cannot consume %s assets" % (engine, asset_spec.format)
    return None


def comma_values(text, lower=False, upper=False):
    """Parse a comma-separated option, preserving first occurrence order."""
    if text is None:
        return None
    values = []
    for raw in text.split(","):
        value = raw.strip()
        if not value:
            continue
        value = value.lower() if lower else value.upper() if upper else value
        if value not in values:
            values.append(value)
    return tuple(values)


def positive_int(text):
    """Argparse type for a strictly positive integer."""
    try:
        value = int(text)
    except ValueError:
        raise argparse.ArgumentTypeError("must be an integer")
    if value < 1:
        raise argparse.ArgumentTypeError("must be >= 1")
    return value


def finite_positive(text):
    """Argparse type for a finite, strictly positive number."""
    try:
        value = float(text)
    except ValueError:
        raise argparse.ArgumentTypeError("must be a number")
    if not math.isfinite(value) or value <= 0.0:
        raise argparse.ArgumentTypeError("must be finite and > 0")
    return value


