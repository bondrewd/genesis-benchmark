def repo_file(relative_path):
    """Return an absolute path for a checked-in/archive-backed repository file."""
    return os.path.join(HERE, *relative_path.split("/"))


def asset(engine, format_name, topology, coordinates=None, definitions=(), parameters=(),
          topology_hmr=None,
          reference=None, amber_scee=None, amber_scnb=None):
    """Build a native archive asset from repository-relative paths."""
    convert = lambda path: repo_file(path) if path else None
    return AssetSpec(
        engine=engine,
        format=format_name,
        topology=convert(topology),
        coordinates=convert(coordinates),
        topology_definitions=tuple(convert(path) for path in definitions),
        parameters=tuple(convert(path) for path in parameters),
        topology_hmr=convert(topology_hmr),
        reference=convert(reference),
        amber_scee=amber_scee,
        amber_scnb=amber_scnb,
        archive_native=True,
    )


def archive_native(system, variant, family, forcefield, water_model, atom_count, charge_e, assets):
    """Declare an archive-backed native variant without assigning a new FF label."""
    return VariantSpec(
        system, variant, family, forcefield, water_model, "explicit",
        atom_count=atom_count, box_angstrom=SYSTEMS[system].box_angstrom,
        assets=tuple(assets), source_charge_e=charge_e,
        source_formal_charge_e=int(round(charge_e)),
        pre_neutralization_charge_e=charge_e,
        pre_neutralization_formal_charge_e=int(round(charge_e)),
        post_neutralization_charge_e=charge_e,
        post_neutralization_formal_charge_e=int(round(charge_e)),
        neutralization_method=("source_preserving" if int(round(charge_e)) == 0
                               else "source_charged"),
    )


