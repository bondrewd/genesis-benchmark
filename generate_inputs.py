def amber_14_scaling(path):
    """Return the uniform SCEE/SCNB factors used by active Amber 1-4 pairs."""
    scee = _amber_flag_floats(path, "SCEE_SCALE_FACTOR")
    scnb = _amber_flag_floats(path, "SCNB_SCALE_FACTOR")
    if not scee and not scnb:
        return 1.2, 2.0
    force = _amber_flag_floats(path, "DIHEDRAL_FORCE_CONSTANT")
    if (not scee or not scnb or len(scee) != len(scnb)
            or len(scee) != len(force)):
        raise GenerationError("%s: inconsistent Amber 1-4 scaling arrays" % path)

    type_indices = []
    for flag in ("DIHEDRALS_INC_HYDROGEN", "DIHEDRALS_WITHOUT_HYDROGEN"):
        terms = _amber_flag_ints(path, flag)
        if len(terms) % 5:
            raise GenerationError("%s: malformed %s array" % (path, flag))
        for offset in range(0, len(terms), 5):
            _, _, third_atom, fourth_atom, type_index = terms[offset:offset + 5]
            if type_index <= 0 or type_index > len(scee):
                raise GenerationError("%s: invalid Amber dihedral type index" % path)
            # Amber uses a negative third atom to suppress the end-group 1-4
            # interaction and a negative fourth atom to mark an improper.  Such
            # records can carry nonzero force constants and placeholder 0/0
            # scale factors, but they do not define a pair NAMD must scale.
            if third_atom < 0 or fourth_atom < 0:
                continue
            type_indices.append(type_index - 1)

    meaningful = [(scee[index], scnb[index]) for index in type_indices]
    if not meaningful or any(electrostatic <= 0.0 or vdw <= 0.0
                             for electrostatic, vdw in meaningful):
        raise GenerationError("%s: invalid meaningful Amber 1-4 scaling factors" % path)
    expected_scee, expected_scnb = meaningful[0]
    if any(abs(value - expected_scee) > 1.0e-8 for value, _ in meaningful):
        raise GenerationError("%s: NAMD cannot represent nonuniform Amber SCEE factors" % path)
    if any(abs(value - expected_scnb) > 1.0e-8 for _, value in meaningful):
        raise GenerationError("%s: NAMD cannot represent nonuniform Amber SCNB factors" % path)
    return expected_scee, expected_scnb


def namd_amber_scaling(asset_spec, topology):
    """Resolve audited archive metadata or verify a prepared Amber topology."""
    expected = (asset_spec.amber_scee, asset_spec.amber_scnb)
    if None not in expected:
        return expected
    if not os.path.isfile(topology):
        raise GenerationError("cannot verify Amber 1-4 scaling: %s" % topology)
    return amber_14_scaling(topology)


def validate_source_transformations(value, spec, label):
    """Validate the explicit source-topology canonicalization audit trail."""
    if not isinstance(value, dict):
        raise GenerationError("%s must be an object" % label)
    native_amber_systems = {"bpti", "ake", "factorix", "stmv", "cellulose"}
    if spec.system not in native_amber_systems:
        if value:
            raise GenerationError("%s must be empty for this native model" % label)
        return

    _exact_keys(value, {
        "amber_box_dimensions", "amber_multiterm_dihedrals",
    }, label)
    box = value["amber_box_dimensions"]
    if not isinstance(box, dict):
        raise GenerationError("%s.amber_box_dimensions must be an object" % label)
    _exact_keys(box, {
        "patched", "scope", "source_box_angstrom_degrees",
        "coordinate_box_angstrom_degrees",
    }, label + ".amber_box_dimensions")
    if not isinstance(box["patched"], bool):
        raise GenerationError("%s.amber_box_dimensions.patched must be boolean" % label)
    expected_scope = "BOX_DIMENSIONS only" if box["patched"] else None
    if box["scope"] != expected_scope:
        raise GenerationError("%s.amber_box_dimensions.scope is inconsistent" % label)
    for key in ("source_box_angstrom_degrees", "coordinate_box_angstrom_degrees"):
        values = box[key]
        if not isinstance(values, list) or len(values) != 6:
            raise GenerationError("%s.amber_box_dimensions.%s must have six values" % (label, key))
        for index, raw in enumerate(values):
            if isinstance(raw, bool) or not isinstance(raw, (int, float)):
                raise GenerationError("%s.amber_box_dimensions.%s is nonnumeric" % (label, key))
            number_value = float(raw)
            if not math.isfinite(number_value) or (index < 3 and number_value <= 0.0):
                raise GenerationError("%s.amber_box_dimensions.%s is invalid" % (label, key))

    dihedrals = value["amber_multiterm_dihedrals"]
    if not isinstance(dihedrals, dict):
        raise GenerationError("%s.amber_multiterm_dihedrals must be an object" % label)
    _exact_keys(dihedrals, {
        "expanded", "changed_flags", "negative_parameter_type_count",
        "original_term_counts", "expanded_term_counts",
    }, label + ".amber_multiterm_dihedrals")
    if not isinstance(dihedrals["expanded"], bool):
        raise GenerationError("%s.amber_multiterm_dihedrals.expanded must be boolean" % label)
    changed_flags = dihedrals["changed_flags"]
    allowed_flags = {
        "DIHEDRAL_PERIODICITY", "DIHEDRALS_INC_HYDROGEN",
        "DIHEDRALS_WITHOUT_HYDROGEN", "POINTERS",
    }
    if (not isinstance(changed_flags, list)
            or changed_flags != sorted(set(changed_flags))
            or any(flag not in allowed_flags for flag in changed_flags)):
        raise GenerationError("%s.amber_multiterm_dihedrals.changed_flags is invalid" % label)
    negative_count = _integer(
        dihedrals, "negative_parameter_type_count",
        label + ".amber_multiterm_dihedrals", minimum=0,
    )
    term_keys = {"DIHEDRALS_INC_HYDROGEN", "DIHEDRALS_WITHOUT_HYDROGEN"}
    for key in ("original_term_counts", "expanded_term_counts"):
        counts = dihedrals[key]
        if not isinstance(counts, dict):
            raise GenerationError("%s.amber_multiterm_dihedrals.%s must be an object" % (label, key))
        if counts:
            _exact_keys(counts, term_keys, label + ".amber_multiterm_dihedrals." + key)
            for term_key in term_keys:
                _integer(counts, term_key, label + ".amber_multiterm_dihedrals." + key,
                         minimum=0)
    if dihedrals["expanded"]:
        if (negative_count < 1 or "DIHEDRAL_PERIODICITY" not in changed_flags
                or set(dihedrals["original_term_counts"]) != term_keys
                or set(dihedrals["expanded_term_counts"]) != term_keys):
            raise GenerationError("%s.amber_multiterm_dihedrals expansion is incomplete" % label)
        for key in term_keys:
            if dihedrals["expanded_term_counts"][key] < dihedrals["original_term_counts"][key]:
                raise GenerationError("%s.amber_multiterm_dihedrals lost terms" % label)
    elif negative_count or changed_flags or dihedrals["original_term_counts"] or dihedrals["expanded_term_counts"]:
        raise GenerationError("%s.amber_multiterm_dihedrals no-op record is inconsistent" % label)


def load_prepared_variant(spec):
    """Load and strictly validate one prepared-variant manifest, or return None."""
    path = manifest_file(spec)
    if not os.path.isfile(path):
        return None
    try:
        with open(path, encoding="utf-8") as manifest_stream:
            payload = json.load(manifest_stream)
    except (OSError, ValueError) as error:
        raise GenerationError("cannot read %s: %s" % (path, error))
    if not isinstance(payload, dict):
        raise GenerationError("%s must contain a JSON object" % path)

    top_level_keys = {
        "schema", "system", "variant", "family", "forcefield", "water_model",
        "solvent", "atom_count", "box_angstrom", "assets", "checksums", "hmr",
        "neutralization", "provenance", "validation",
    }
    _exact_keys(payload, top_level_keys, path)

    expected = {
        "schema": 1,
        "system": spec.system,
        "variant": spec.variant,
        "family": spec.family,
        "forcefield": spec.forcefield,
        "water_model": spec.water_model,
        "solvent": spec.solvent,
    }
    for key, expected_value in expected.items():
        if payload.get(key) != expected_value:
            raise GenerationError(
                "%s: %s must be %r, got %r" % (path, key, expected_value, payload.get(key))
            )

    atom_count = payload.get("atom_count")
    if isinstance(atom_count, bool) or not isinstance(atom_count, int) or atom_count < 1:
        raise GenerationError("%s: atom_count must be a positive integer" % path)
    box = _box(payload.get("box_angstrom"), path + ": box_angstrom")

    neutralization = payload.get("neutralization")
    if not isinstance(neutralization, dict):
        raise GenerationError("%s: neutralization must be an object" % path)
    neutralization_keys = {
        "method", "seed", "tolerance_e", "min_ion_separation_nm",
        "min_ion_solute_distance_nm", "source_charge_e",
        "source_formal_charge_e", "pre_neutralization_charge_e",
        "pre_neutralization_formal_charge_e", "post_neutralization_charge_e",
        "post_neutralization_formal_charge_e", "neutralization_ion",
        "neutralization_ion_charge_e", "neutralization_ion_count",
        "replaced_water_count", "existing_ions", "water_count_before",
        "water_count_after", "selected_water_residue_indices",
        "selected_water_oxygen_positions_nm",
    }
    _exact_keys(neutralization, neutralization_keys, path + ": neutralization")
    tolerance = _finite_number(neutralization, "tolerance_e", path + ": neutralization",
                               minimum=0.0)
    if tolerance <= 0.0 or tolerance > 1.0e-3:
        raise GenerationError("%s: neutralization.tolerance_e must be in (0, 1e-3]" % path)
    source_charge = _finite_charge(neutralization, "source_charge_e", path)
    source_formal = _formal_charge(neutralization, "source_formal_charge_e", path)
    pre_charge = _finite_charge(neutralization, "pre_neutralization_charge_e", path)
    pre_formal = _formal_charge(neutralization, "pre_neutralization_formal_charge_e", path)
    post_charge = _finite_charge(neutralization, "post_neutralization_charge_e", path)
    post_formal = _formal_charge(neutralization, "post_neutralization_formal_charge_e", path)
    if abs(source_charge - source_formal) > tolerance:
        raise GenerationError("%s: source raw/formal charges exceed declared tolerance" % path)
    if abs(pre_charge - pre_formal) > tolerance:
        raise GenerationError("%s: pre-neutralization raw/formal charges exceed declared tolerance" % path)
    if abs(post_charge - post_formal) > tolerance:
        raise GenerationError("%s: post-neutralization raw/formal charges exceed declared tolerance" % path)
    if source_formal != pre_formal:
        raise GenerationError("%s: reparameterization changed formal charge (%d -> %d)" %
                              (path, source_formal, pre_formal))

    ion = neutralization.get("neutralization_ion")
    ion_charge = neutralization.get("neutralization_ion_charge_e")
    ion_count = neutralization.get("neutralization_ion_count")
    water_count = neutralization.get("replaced_water_count")
    method = neutralization.get("method")
    for key, value in (("neutralization_ion_count", ion_count),
                       ("replaced_water_count", water_count)):
        if isinstance(value, bool) or not isinstance(value, int) or value < 0:
            raise GenerationError("%s: %s must be a nonnegative integer" % (path, key))
    if ion_count != water_count:
        raise GenerationError("%s: replaced_water_count must equal neutralization_ion_count" % path)
    seed = neutralization.get("seed")
    if seed is not None and (not isinstance(seed, str) or not seed):
        raise GenerationError("%s: neutralization.seed must be a nonempty string or null" % path)
    min_ion_separation = _finite_number(
        neutralization, "min_ion_separation_nm", path + ": neutralization",
        minimum=0.0, allow_null=True,
    )
    min_ion_solute = _finite_number(
        neutralization, "min_ion_solute_distance_nm", path + ": neutralization",
        minimum=0.0, allow_null=True,
    )
    existing_ions = neutralization.get("existing_ions")
    if not isinstance(existing_ions, dict) or any(
            not isinstance(name, str) or not name
            or isinstance(count, bool) or not isinstance(count, int) or count < 0
            for name, count in existing_ions.items()):
        raise GenerationError("%s: neutralization.existing_ions must map names to counts" % path)
    water_before = _integer(neutralization, "water_count_before", path, minimum=0)
    water_after = _integer(neutralization, "water_count_after", path, minimum=0)
    selected_indices = neutralization.get("selected_water_residue_indices")
    selected_positions = neutralization.get("selected_water_oxygen_positions_nm")
    if not isinstance(selected_indices, list) or any(
            isinstance(value, bool) or not isinstance(value, int) or value < 0
            for value in selected_indices):
        raise GenerationError("%s: selected water residue indices are invalid" % path)
    if len(set(selected_indices)) != len(selected_indices):
        raise GenerationError("%s: selected water residue indices must be unique" % path)
    if not isinstance(selected_positions, list):
        raise GenerationError("%s: selected water oxygen positions must be an array" % path)
    for index, position in enumerate(selected_positions):
        if not isinstance(position, list) or len(position) != 3 or any(
                isinstance(value, bool) or not isinstance(value, (int, float))
                or not math.isfinite(float(value)) for value in position):
            raise GenerationError("%s: invalid selected water position %d" % (path, index))
    if len(selected_indices) != ion_count or len(selected_positions) != ion_count:
        raise GenerationError("%s: selected-water metadata count does not match counterions" % path)
    if ion is not None and ion not in ("Na+", "Cl-"):
        raise GenerationError("%s: neutralization ion must be Na+, Cl-, or null" % path)
    if ion_charge is not None and (
            isinstance(ion_charge, bool) or not isinstance(ion_charge, int)
            or ion_charge not in (-1, 1)):
        raise GenerationError("%s: neutralization ion charge must be +1, -1, or null" % path)
    if post_formal != 0:
        raise GenerationError("%s: post-neutralization formal charge must be zero" % path)
    expected_count = abs(pre_formal)
    if ion_count != expected_count:
        raise GenerationError("%s: expected %d counterions from formal charge, got %d" %
                              (path, expected_count, ion_count))
    if expected_count == 0:
        if (method != "none_required" or ion is not None or ion_charge is not None
                or seed is not None or min_ion_separation is not None
                or min_ion_solute is not None or abs(post_charge - pre_charge) > 1.0e-6):
            raise GenerationError("%s: invalid none_required neutralization metadata" % path)
    else:
        expected_ion = "Na+" if pre_formal < 0 else "Cl-"
        expected_ion_charge = 1 if pre_formal < 0 else -1
        if method != "replace_waters":
            raise GenerationError("%s: charged native variants require replace_waters" % path)
        if ion != expected_ion or ion_charge != expected_ion_charge:
            raise GenerationError("%s: counterion must be %s with charge %+d" %
                                  (path, expected_ion, expected_ion_charge))
        expected_seed = "genesis-benchmark-neutralize-v1:%s" % spec.system
        if seed != expected_seed or min_ion_separation is None or min_ion_separation <= 0.0:
            raise GenerationError("%s: replace_waters requires seed and positive ion separation" % path)
        if min_ion_solute is None or min_ion_solute <= 0.0 or abs(post_charge) > 1.0e-6:
            raise GenerationError("%s: replace_waters ion placement/charge validation failed" % path)
    if water_before - water_after != ion_count:
        raise GenerationError("%s: water counts do not match replacements" % path)

    asset_map = payload.get("assets")
    if not isinstance(asset_map, dict) or not asset_map:
        raise GenerationError("%s: assets must be a nonempty object" % path)
    extra_engines = sorted(set(asset_map) - set(ENGINE_ORDER))
    if extra_engines:
        raise GenerationError("%s: assets has unexpected engines %s" % (path, ",".join(extra_engines)))

    manifest_dir = os.path.dirname(path)
    assets = []
    for engine in (name for name in ENGINE_ORDER if name in asset_map):
        record = asset_map[engine]
        if spec.family == "CHARMM" and engine in ("OPENMM", "GROMACS", "AMBER"):
            raise GenerationError(
                "%s: native CHARMM %s assets lack an exact validated switching representation" %
                (path, engine)
            )
        if not isinstance(record, dict):
            raise GenerationError("%s: assets.%s must be an object" % (path, engine))
        format_name = normalized_format(record.get("format", ""))
        if not format_name:
            raise GenerationError("%s: assets.%s.format is required" % (path, engine))
        if record.get("format") != format_name:
            raise GenerationError("%s: assets.%s.format must use its canonical uppercase spelling" %
                                  (path, engine))
        allowed_formats = {
            "GENESIS": {"AMBER", "CHARMM", "GROAMBER"},
            "OPENMM": {"AMBER", "CHARMM"},
            "GROMACS": {"GROMACS"},
            "AMBER": {"AMBER", "CHAMBER"},
            "NAMD": {"AMBER", "CHARMM"},
        }[engine]
        if format_name not in allowed_formats:
            raise GenerationError(
                "%s: assets.%s.format %r is not one of %s" %
                (path, engine, record.get("format"), ",".join(sorted(allowed_formats)))
            )
        prefix = "%s: assets.%s" % (path, engine)
        if engine == "GENESIS":
            required = ("format", "topology", "coordinates", "topology_definitions", "parameters")
            _exact_keys(record, required, prefix)
            item = AssetSpec(
                engine, format_name,
                _manifest_path(manifest_dir, record["topology"], prefix + ".topology"),
                _manifest_path(manifest_dir, record["coordinates"], prefix + ".coordinates"),
                _path_list(manifest_dir, record["topology_definitions"], prefix + ".topology_definitions"),
                _path_list(manifest_dir, record["parameters"], prefix + ".parameters"),
            )
        elif engine == "OPENMM":
            required = {"format", "topology", "coordinates"}
            if format_name == "CHARMM":
                required.update(("topology_definitions", "parameters"))
            _exact_keys(record, required, prefix)
            item = AssetSpec(
                engine, format_name,
                _manifest_path(manifest_dir, record["topology"], prefix + ".topology"),
                _manifest_path(manifest_dir, record["coordinates"], prefix + ".coordinates"),
                topology_definitions=(
                    _path_list(manifest_dir, record["topology_definitions"],
                               prefix + ".topology_definitions")
                    if format_name == "CHARMM" else ()
                ),
                parameters=(
                    _path_list(manifest_dir, record["parameters"], prefix + ".parameters")
                    if format_name == "CHARMM" else ()
                ),
            )
        else:
            required = {"format", "topology", "coordinates"}
            if engine in ("AMBER", "NAMD"):
                required.add("topology_hmr")
            if engine == "NAMD":
                required.add("parameters")
                coordinate_extension = os.path.splitext(str(record.get("coordinates", "")))[1].lower()
                if format_name == "CHARMM" and coordinate_extension in (".coor", ".bin"):
                    required.add("coordinate_reference")
            expected_keys = required
            if engine == "GROMACS" and "topology_hmr" in record:
                expected_keys = required | {"topology_hmr"}
            _exact_keys(record, expected_keys, prefix)
            parameter_paths = ()
            if engine == "NAMD":
                parameter_paths = _path_list(manifest_dir, record["parameters"], prefix + ".parameters")
            item = AssetSpec(
                engine, format_name,
                _manifest_path(manifest_dir, record["topology"], prefix + ".topology"),
                _manifest_path(manifest_dir, record["coordinates"], prefix + ".coordinates"),
                parameters=parameter_paths,
                topology_hmr=(
                    _manifest_path(manifest_dir, record["topology_hmr"], prefix + ".topology_hmr")
                    if engine in ("AMBER", "NAMD") or "topology_hmr" in record else None
                ),
                coordinate_reference=(
                    _manifest_path(manifest_dir, record["coordinate_reference"],
                                   prefix + ".coordinate_reference")
                    if "coordinate_reference" in record else None
                ),
            )
            if (item.coordinate_reference is not None
                    and os.path.splitext(item.coordinate_reference)[1].lower() != ".pdb"):
                raise GenerationError(
                    "%s.coordinate_reference must be a PDB scaffold" % prefix
                )
        assets.append(item)

    asset_names = set()
    for record in asset_map.values():
        for key, value in record.items():
            if key == "format":
                continue
            if isinstance(value, str):
                asset_names.add(value)
            else:
                asset_names.update(value)
    checksums = payload.get("checksums")
    if not isinstance(checksums, dict) or set(checksums) != asset_names:
        raise GenerationError("%s: checksums keys must exactly match every asset path" % path)
    for name in sorted(asset_names):
        expected_digest = checksums[name]
        if not _valid_sha256(expected_digest):
            raise GenerationError("%s: invalid SHA-256 for %s" % (path, name))
        resolved = _manifest_path(manifest_dir, name, path + ": checksums." + name)
        if _sha256(resolved) != expected_digest:
            raise GenerationError("%s: checksum mismatch for %s" % (path, name))

    hmr = payload.get("hmr")
    if not isinstance(hmr, dict):
        raise GenerationError("%s: hmr must be an object" % path)
    _exact_keys(hmr, {
        "method", "hydrogen_mass_dalton", "particles_with_changed_mass",
        "water_particles_with_changed_mass", "total_mass_delta_dalton",
    }, path + ": hmr")
    if hmr["method"] != HMR_METHOD:
        raise GenerationError("%s: hmr.method is not the authoritative native HMR method" % path)
    hmr_hydrogen_mass = _finite_number(
        hmr, "hydrogen_mass_dalton", path + ": hmr", minimum=0.0,
    )
    if abs(hmr_hydrogen_mass - HMR_HYDROGEN_MASS_DALTON) > 1.0e-12:
        raise GenerationError(
            "%s: HMR hydrogen mass must be exactly %s Da" %
            (path, HMR_HYDROGEN_MASS_DALTON)
        )
    _integer(hmr, "particles_with_changed_mass", path + ": hmr", minimum=1)
    if _integer(hmr, "water_particles_with_changed_mass", path + ": hmr", minimum=0) != 0:
        raise GenerationError("%s: HMR must not repartition rigid-water hydrogens" % path)
    if abs(_finite_number(hmr, "total_mass_delta_dalton", path + ": hmr")) > 1.0e-5:
        raise GenerationError("%s: HMR did not conserve total mass" % path)

    provenance = payload.get("provenance")
    if not isinstance(provenance, dict):
        raise GenerationError("%s: provenance must be an object" % path)
    _exact_keys(provenance, {
        "preparation_script", "preparation_script_version",
        "preparation_script_sha256", "source_transformations", "source_archive",
        "source_atom_count", "coordinate_source", "forcefield_files",
        "charmm_toppar_files", "openmm_version", "openmm_git_revision",
        "openmm_release", "parmed_version",
    }, path + ": provenance")
    if provenance["preparation_script"] != "prepare_variants.py":
        raise GenerationError("%s: unexpected preparation script" % path)
    preparation_version = _integer(
        provenance, "preparation_script_version", path + ": provenance", minimum=1,
    )
    if preparation_version != PREPARATION_SCRIPT_VERSION:
        raise GenerationError(
            "%s: prepared assets use script version %d, expected %d; rebuild the system" %
            (path, preparation_version, PREPARATION_SCRIPT_VERSION)
        )
    preparation_script_sha256 = provenance["preparation_script_sha256"]
    if not _valid_sha256(preparation_script_sha256):
        raise GenerationError("%s: invalid preparation script SHA-256" % path)
    preparation_script_path = os.path.join(HERE, "prepare_variants.py")
    if not os.path.isfile(preparation_script_path):
        raise GenerationError("%s: prepare_variants.py is missing" % path)
    if _sha256(preparation_script_path) != preparation_script_sha256:
        raise GenerationError(
            "%s: prepared assets do not match the current prepare_variants.py" % path
        )
    validate_source_transformations(
        provenance["source_transformations"], spec,
        path + ": provenance.source_transformations",
    )
    source_atom_count = _integer(
        provenance, "source_atom_count", path + ": provenance", minimum=1,
    )
    native_source = ARCHIVE_FALLBACKS.get((spec.system, spec.variant))
    if native_source is None:
        raise GenerationError("%s: prepared model has no pinned native source" % path)
    if source_atom_count != native_source.atom_count:
        raise GenerationError(
            "%s: provenance.source_atom_count does not match the pinned native archive" % path
        )
    if source_formal != native_source.source_formal_charge_e:
        raise GenerationError(
            "%s: source formal charge does not match the pinned native archive" % path
        )
    if abs(source_charge - native_source.source_charge_e) > 1.0e-3:
        raise GenerationError(
            "%s: source charge does not match the pinned native archive" % path
        )
    expected_toolchain = {
        "openmm_version": EXPECTED_OPENMM_VERSION,
        "openmm_git_revision": EXPECTED_OPENMM_GIT_REVISION,
        "openmm_release": EXPECTED_OPENMM_RELEASE,
        "parmed_version": EXPECTED_PARMED_VERSION,
    }
    for key, expected_value in expected_toolchain.items():
        if provenance[key] != expected_value:
            raise GenerationError(
                "%s: provenance.%s must be %r, got %r" %
                (path, key, expected_value, provenance[key])
            )
    source_archive = provenance.get("source_archive")
    coordinate_source = provenance.get("coordinate_source")
    if not isinstance(source_archive, dict) or not isinstance(coordinate_source, dict):
        raise GenerationError("%s: source provenance records must be objects" % path)
    _exact_keys(source_archive, {"path", "sha256"}, path + ": provenance.source_archive")
    _exact_keys(coordinate_source, {"path", "sha256", "legacy_restart_used"},
                path + ": provenance.coordinate_source")
    expected_archive = "data/%s.tgz" % spec.system
    if source_archive.get("path") != expected_archive:
        raise GenerationError("%s: source archive path must be %s" % (path, expected_archive))
    if not str(coordinate_source.get("path", "")).startswith(expected_archive + "::"):
        raise GenerationError(
            "%s: coordinate source must identify a member of %s" % (path, expected_archive)
        )
    if not isinstance(coordinate_source["legacy_restart_used"], bool):
        raise GenerationError("%s: legacy_restart_used must be boolean" % path)
    verify_provenance_record(source_archive, path + ": provenance.source_archive")
    verify_archive_pin(spec.system)
    if source_archive["sha256"] != ARCHIVE_PINS[spec.system]["archive_sha256"]:
        raise GenerationError("%s: source archive is not the pinned native archive" % path)
    verify_provenance_record(
        coordinate_source, path + ": provenance.coordinate_source",
        require_archive_member=True,
    )
    for collection_name in ("forcefield_files", "charmm_toppar_files"):
        collection = provenance.get(collection_name)
        if not isinstance(collection, list):
            raise GenerationError("%s: provenance.%s must be an array" % (path, collection_name))
        for index, record in enumerate(collection):
            label = "%s: provenance.%s[%d]" % (path, collection_name, index)
            if not isinstance(record, dict):
                raise GenerationError("%s must be an object" % label)
            _exact_keys(record, {"path", "sha256"}, label)
            verify_provenance_record(record, label)
    if spec.family == "AMBER" and provenance["charmm_toppar_files"]:
        raise GenerationError("%s: AMBER variants cannot claim CHARMM toppar files" % path)

    validation = payload.get("validation")
    if not isinstance(validation, dict):
        raise GenerationError("%s: validation must be an object" % path)
    _exact_keys(validation, {"status", "canonical", "assets", "representative_numerical"},
                path + ": validation")
    if validation["status"] != "pass":
        raise GenerationError("%s: validation.status must be pass" % path)
    canonical = validation.get("canonical")
    if not isinstance(canonical, dict):
        raise GenerationError("%s: validation.canonical must be an object" % path)
    _exact_keys(canonical, {
        "atom_count", "raw_charge_e", "formal_charge_e", "box_angstrom",
        "bonded_term_counts", "exception_count", "constraint_count",
    }, path + ": validation.canonical")
    if _integer(canonical, "atom_count", path + ": validation.canonical", minimum=1) != atom_count:
        raise GenerationError("%s: canonical atom count mismatch" % path)
    canonical_charge = _finite_charge(canonical, "raw_charge_e", path)
    canonical_formal = _formal_charge(canonical, "formal_charge_e", path)
    if canonical_formal != post_formal or abs(canonical_charge - post_charge) > tolerance:
        raise GenerationError("%s: canonical charge mismatch" % path)
    canonical_box = _box(canonical.get("box_angstrom"), path + ": validation.canonical.box_angstrom")
    if canonical_box != box:
        raise GenerationError("%s: canonical box mismatch" % path)
    bonded_counts = canonical.get("bonded_term_counts")
    if not isinstance(bonded_counts, dict):
        raise GenerationError("%s: canonical bonded_term_counts must be an object" % path)
    _exact_keys(bonded_counts, {"bonds", "angles", "proper_dihedrals", "impropers", "cmaps"},
                path + ": validation.canonical.bonded_term_counts")
    for key in bonded_counts:
        _integer(bonded_counts, key, path + ": validation.canonical.bonded_term_counts", minimum=0)
    _integer(canonical, "exception_count", path + ": validation.canonical", minimum=0)
